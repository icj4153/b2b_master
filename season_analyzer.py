# 꼼꼼한 분석을 위해 글자가 긴 키워드부터 찾도록 자동 정렬 (예: '대저토마토'를 '토마토'보다 먼저 찾음)
SORTED_SEASON_KEYWORDS = sorted(SEASON_MAP.keys(), key=len, reverse=True)


def get_season_info(product_name):
    """상품명에서 제철 메인키워드와 제철 월 정보를 찾는다."""
    name = str(product_name).replace(" ", "")
    for keyword in SORTED_SEASON_KEYWORDS:
        if keyword in name:
            return pd.Series([keyword, SEASON_MAP[keyword]])
    return pd.Series(["기타/상시", "시즌무관"])


def add_seasonality_columns(df, product_column="상품명"):
    """통합 상품 DataFrame에 메인키워드와 제철(월) 컬럼을 추가한다."""
    if product_column not in df.columns:
        raise KeyError(f"'{product_column}' 컬럼이 없어 제철 태그를 붙일 수 없습니다.")

    result = df.copy()
    result[['메인키워드', '제철(월)']] = result[product_column].apply(get_season_info)
    return result


BASE_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = Path(os.getenv("B2B_OUTPUT_DIR", str(BASE_DIR / "output")))


def find_latest_integrated_file():
    files = list(OUTPUT_DIR.glob("전체품목_통합데이터_*.xlsx"))
    if not files:
        return None
    return max(files, key=lambda path: path.stat().st_mtime)


def apply_seasonality(file_path=None, output_path=None):
    print("[season] 상품명 키워드 분석 및 제철 매핑을 시작합니다...")

    source_path = Path(file_path) if file_path else find_latest_integrated_file()
    if source_path is None or not source_path.exists():
        print("[season] 통합 데이터 파일이 없습니다. 먼저 b2b_excel.py로 데이터 통합을 진행해주세요.")
        return

    # 모든 데이터를 문자로 안전하게 로드
    df = pd.read_excel(source_path, dtype=str)

    # 18,000개 데이터에 '메인키워드'와 '제철분류' 컬럼 자동 생성
    print("[season] 상품에 제철 태그를 붙이는 중...")
    df = add_seasonality_columns(df)

    target_path = Path(output_path) if output_path else source_path
    df.to_excel(target_path, index=False)
    print(f"\n[season] 분석 완료: {target_path} 파일에 키워드와 제철 데이터가 추가되었습니다.")


if __name__ == "__main__":
    apply_seasonality()
